def _schema_types(schema: dict) -> set[str]:
    """Extract JSON Schema types from either a direct type or anyOf schema."""
    types: set[str] = set()
    if "type" in schema:
        types.add(schema["type"])
    for item in schema.get("anyOf", []):
        if "type" in item:
            types.add(item["type"])
    return types


